func TestBuildPlanAddsIndependentChainBeforeVendorChains(t *testing.T) {
	current := strings.Join([]string{
		"-P INPUT ACCEPT",
		"-N CEMS_COMMON_INPUT",
		"-N KSC_PUBLIC_INPUT",
		"-A INPUT -j CEMS_COMMON_INPUT",
		"-A INPUT -i eno1 -j KSC_PUBLIC_INPUT",
		"-A CEMS_COMMON_INPUT -p tcp --dport 3389 -j DROP",
		"-A CEMS_COMMON_INPUT -p tcp --dport 445 -j ACCEPT",
	}, "\n")

	plan, err := firewall.BuildPlan(current)
	if err != nil {
		t.Fatalf("BuildPlan() error = %v", err)
	}
	if len(plan) != 10 {
		t.Fatalf("commands = %d, want 10: %#v", len(plan), plan)
	}
	if !reflect.DeepEqual(plan[0].Args, []string{"-N", "SEC_REMEDIATOR_INPUT"}) {
		t.Fatalf("first command = %#v", plan[0].Args)
	}
	if !reflect.DeepEqual(plan[1].Args, []string{"-I", "INPUT", "1", "-j", "SEC_REMEDIATOR_INPUT"}) {
		t.Fatalf("jump command = %#v", plan[1].Args)
	}
	for _, command := range plan {
		joined := strings.Join(command.Args, " ")
		if strings.Contains(joined, "CEMS_") || strings.Contains(joined, "KSC_") {
			t.Fatalf("plan modifies vendor chain: %s", joined)
		}
	}
}

