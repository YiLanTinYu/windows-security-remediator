func TestBuildPlanRemovesDuplicateManagedJumpAndRules(t *testing.T) {
	current := strings.Join([]string{
		"-N SEC_REMEDIATOR_INPUT",
		"-A INPUT -j CEMS_COMMON_INPUT",
		"-A INPUT -j SEC_REMEDIATOR_INPUT",
		"-A INPUT -j SEC_REMEDIATOR_INPUT",
		"-A SEC_REMEDIATOR_INPUT -p tcp --dport 22 -m comment --comment SecurityRemediator -j DROP",
		"-A SEC_REMEDIATOR_INPUT -p tcp --dport 22 -m comment --comment SecurityRemediator -j DROP",
	}, "\n")

	plan, err := firewall.BuildPlan(current)
	if err != nil {
		t.Fatalf("BuildPlan() error = %v", err)
	}
	joined := make([]string, 0, len(plan))
	for _, command := range plan {
		joined = append(joined, strings.Join(command.Args, " "))
	}
	for _, want := range []string{
		"-I INPUT 1 -j SEC_REMEDIATOR_INPUT",
		"-D INPUT 4",
		"-D INPUT 3",
		"-D SEC_REMEDIATOR_INPUT -p tcp --dport 22 -m comment --comment SecurityRemediator -j DROP",
	} {
		if !contains(joined, want) {
			t.Errorf("plan missing %q: %#v", want, joined)
		}
	}
}

func contains(items []string, expected string) bool {
	for _, item := range items {
		if item == expected {
			return true
		}
	}
	return false
}
